import { hasOwn, isLikelySecretKey, detectRealSecretInExample } from '../security/secretHygiene.js';
import type { SchemaPropertySpec } from '../scanner/schemaValidator.js';

export interface SerializeEnvOptions {
  sortKeys?: boolean;
  headerComment?: string;
}

function needsDoubleQuotes(val: string): boolean {
  if (val.length === 0) {
    return false;
  }
  if (
    val.startsWith(' ') ||
    val.startsWith('\t') ||
    val.endsWith(' ') ||
    val.endsWith('\t')
  ) {
    return true;
  }
  for (let i = 0; i < val.length; i++) {
    const code = val.charCodeAt(i);
    if (
      code === 0x0a || // \n
      code === 0x0d || // \r
      code === 0x09 || // \t
      code === 0x22 || // "
      code === 0x27 || // '
      code === 0x23 || // #
      code === 0x24 || // $
      code === 0x5c    // \
    ) {
      return true;
    }
  }
  return false;
}

export function formatEnvValue(val: string): string {
  if (!needsDoubleQuotes(val)) {
    return val;
  }
  let escaped = '"';
  for (let i = 0; i < val.length; i++) {
    const code = val.charCodeAt(i);
    if (code === 0x0a) {
      escaped += '\\n';
    } else if (code === 0x0d) {
      escaped += '\\r';
    } else if (code === 0x09) {
      escaped += '\\t';
    } else if (code === 0x22) {
      escaped += '\\"';
    } else if (code === 0x5c) {
      escaped += '\\\\';
    } else if (code === 0x24) {
      escaped += '\\$';
    } else {
      escaped += val[i]!;
    }
  }
  escaped += '"';
  return escaped;
}

export function serializeEnv(
  record: Record<string, string>,
  options: SerializeEnvOptions = {}
): string {
  const keys = Object.keys(record);
  if (options.sortKeys) {
    keys.sort();
  }
  const lines: string[] = [];
  if (options.headerComment) {
    const commentLines = options.headerComment.split('\n');
    for (let i = 0; i < commentLines.length; i++) {
      lines.push(`# ${commentLines[i]!}`);
    }
    lines.push('');
  }
  for (let i = 0; i < keys.length; i++) {
    const key = keys[i]!;
    if (!hasOwn(record, key)) continue;
    const val = record[key]!;
    lines.push(`${key}=${formatEnvValue(val)}`);
  }
  return lines.join('\n') + (lines.length > 0 ? '\n' : '');
}

export interface ScrubbedExampleParams {
  allKeys: string[];
  existingExampleValues?: Record<string, string>;
  schemaProperties?: Record<string, SchemaPropertySpec>;
}

/**
 * Generates a strictly scrubbed `.env.example` from discovered variable NAMES and optional schema metadata.
 * SECURITY INVARIANT: Real `.env` values are NEVER passed to or read by this function.
 */
export function generateScrubbedExample(params: ScrubbedExampleParams): string {
  const sortedKeys = [...new Set(params.allKeys)].sort();
  const lines: string[] = [
    '# Generated by env-guard sync --write-example',
    '# Populate secret and environment-specific values in your local .env file.',
    ''
  ];

  for (let i = 0; i < sortedKeys.length; i++) {
    const key = sortedKeys[i]!;
    const schemaSpec =
      params.schemaProperties && hasOwn(params.schemaProperties, key)
        ? params.schemaProperties[key]
        : undefined;

    const isSecret = schemaSpec?.type === 'secret' || isLikelySecretKey(key);

    if (schemaSpec?.description) {
      lines.push(`# ${schemaSpec.description.replaceAll('\n', ' ')}`);
    }

    let safePlaceholder = '';

    if (isSecret) {
      // Never populate secret keys with any value in .env.example
      safePlaceholder = '';
    } else if (
      params.existingExampleValues &&
      hasOwn(params.existingExampleValues, key) &&
      params.existingExampleValues[key] !== undefined &&
      detectRealSecretInExample(key, params.existingExampleValues[key]!) === null
    ) {
      // Preserve existing non-secret placeholder from .env.example if safe
      safePlaceholder = params.existingExampleValues[key]!;
    } else if (schemaSpec?.default !== undefined && schemaSpec.default !== null) {
      const defStr = String(schemaSpec.default);
      if (detectRealSecretInExample(key, defStr) === null) {
        safePlaceholder = defStr;
      }
    } else if (schemaSpec) {
      switch (schemaSpec.type) {
        case 'port':
          safePlaceholder = '3000';
          break;
        case 'bool':
          safePlaceholder = 'false';
          break;
        case 'int':
          safePlaceholder = '0';
          break;
        case 'url':
          safePlaceholder = 'https://example.com';
          break;
        case 'enum':
          safePlaceholder =
            schemaSpec.values && schemaSpec.values.length > 0
              ? schemaSpec.values[0]!
              : '';
          break;
        case 'email':
        case 'string':
        default:
          safePlaceholder = '';
          break;
      }
    }

    lines.push(`${key}=${formatEnvValue(safePlaceholder)}`);
  }

  return lines.join('\n') + '\n';
}
